package locksnap

import (
	"os"
	"path/filepath"
	"testing"
)

const samplePackageJSON = `{
  "name": "demo",
  "dependencies": { "lodash": "^4.17.0" },
  "devDependencies": { "react": "^18.0.0" }
}`

func writeProject(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	for name, content := range files {
		path := filepath.Join(dir, name)
		os.MkdirAll(filepath.Dir(path), 0o755)
		if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

// --- npm v3 (modern) ----------------------------------------------------

const npmV3Lock = `{
  "name": "demo",
  "lockfileVersion": 3,
  "packages": {
    "": { "name": "demo", "version": "1.0.0" },
    "node_modules/lodash": {
      "version": "4.17.21",
      "integrity": "sha512-aaa"
    },
    "node_modules/react": {
      "version": "18.2.0",
      "integrity": "sha512-bbb"
    },
    "node_modules/react/node_modules/loose-envify": {
      "version": "1.4.0",
      "integrity": "sha512-ccc"
    }
  }
}`

func TestScanner_NpmV3(t *testing.T) {
	dir := writeProject(t, map[string]string{
		"package.json":      samplePackageJSON,
		"package-lock.json": npmV3Lock,
	})
	deps, err := NewScanner().ScanProject(dir)
	if err != nil {
		t.Fatal(err)
	}
	if len(deps) != 3 {
		t.Fatalf("expected 3 deps, got %d: %+v", len(deps), deps)
	}
	// Sorted by name.
	if deps[0].Name != "lodash" || deps[1].Name != "loose-envify" || deps[2].Name != "react" {
		t.Errorf("unexpected order/names: %+v", deps)
	}
	// Integrity preserved.
	if deps[0].Integrity != "sha512-aaa" {
		t.Errorf("integrity lost: %+v", deps[0])
	}
	// Direct flag from package.json.
	if !deps[0].Direct || !deps[2].Direct || deps[1].Direct {
		t.Errorf("direct flags wrong: lodash=%v react=%v loose-envify=%v",
			deps[0].Direct, deps[2].Direct, deps[1].Direct)
	}
}

