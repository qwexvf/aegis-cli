// --- pnpm ---------------------------------------------------------------

const pnpmLock = `lockfileVersion: '6.0'

dependencies:
  lodash:
    specifier: ^4.17.0
    version: 4.17.21

packages:

  /lodash@4.17.21:
    resolution: {integrity: sha512-aaa}
    dev: false

  /react@18.2.0:
    resolution: {integrity: sha512-bbb}

  /loose-envify@1.4.0(react@18.2.0):
    resolution: {integrity: sha512-ccc}

  /@types/lodash@4.14.0:
    resolution: {integrity: sha512-ddd}
    dev: true

settings:
  autoInstallPeers: true
`

func TestScanner_Pnpm(t *testing.T) {
	dir := writeProject(t, map[string]string{
		"package.json":   samplePackageJSON,
		"pnpm-lock.yaml": pnpmLock,
	})
	deps, err := NewScanner().ScanProject(dir)
	if err != nil {
		t.Fatal(err)
	}
	if len(deps) != 4 {
		t.Fatalf("expected 4 deps, got %d: %+v", len(deps), deps)
	}
	names := make([]string, len(deps))
	for i, d := range deps {
		names[i] = d.Name
	}
	want := []string{"@types/lodash", "lodash", "loose-envify", "react"}
	for i, w := range want {
		if names[i] != w {
			t.Errorf("dep[%d] name = %q, want %q (full: %v)", i, names[i], w, names)
		}
	}
}

